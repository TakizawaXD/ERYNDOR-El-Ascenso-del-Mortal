# accented capitals: accent mark drawn in the extra row above (glyph height 9 = 2 rows of accent space)
ACC = {'Á': 'A', 'É': 'E', 'Í': 'I', 'Ó': 'O', 'Ú': 'U', 'Ñ': 'N', 'Ü': 'U'}

CW, CH = 8, 10          # atlas cell
ASC = 2                 # rows reserved above caps for accents


def glyph_img(ch):
    im = Image.new('RGBA', (CW, CH), (0, 0, 0, 0))
    base = ACC.get(ch, ch)
    rows = G[base]
    w = len(rows[0])
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == '#':
                im.putpixel((x, y + ASC), (255, 255, 255, 255))
    if ch in ACC:
        if ch == 'Ñ':
            for x in range(w - 1):
                im.putpixel((x + (x > 1), 0), (255, 255, 255, 255))
        elif ch == 'Ü':
            im.putpixel((1, 0), (255, 255, 255, 255)); im.putpixel((w - 2, 0), (255, 255, 255, 255))
        else:
            cx = w // 2
            im.putpixel((cx + 1, 0), (255, 255, 255, 255)); im.putpixel((cx, 1), (255, 255, 255, 255))
    return im, w


def build(out_png, out_json):
    chars = list(G.keys()) + list(ACC.keys())
    cols = 16
    rows = (len(chars) + cols - 1) // cols
    atlas = Image.new('RGBA', (cols * CW, rows * CH), (0, 0, 0, 0))
    meta = []
    for i, ch in enumerate(chars):
        g, w = glyph_img(ch)
        x, y = (i % cols) * CW, (i // cols) * CH
        atlas.alpha_composite(g, (x, y))
        meta.append(dict(c=ord(ch), x=x, y=y, w=w, adv=w + 1))
    os.makedirs(os.path.dirname(out_png), exist_ok=True)
    atlas.save(out_png)
    json.dump(dict(cellW=CW, cellH=CH, ascent=ASC, size=CH, glyphs=meta), open(out_json, 'w'))
    return atlas.size, len(chars)


if __name__ == '__main__':
    import sys
    root = sys.argv[1]
    print(build(os.path.join(root, 'pixelfont.png'), os.path.join(root, 'pixelfont.json')))
