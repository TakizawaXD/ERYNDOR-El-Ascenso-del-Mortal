ACC = {'Á': 'A', 'É': 'E', 'Í': 'I', 'Ó': 'O', 'Ú': 'U', 'Ñ': 'N', 'Ü': 'U',
       'á': 'a', 'é': 'e', 'í': 'i', 'ó': 'o', 'ú': 'u', 'ñ': 'n', 'ü': 'u'}

CW, CH = 8, 10
TOP = 3                  # first cap row


def rows_of(ch):
    for t in (U, L, D):
        if ch in t: return t[ch]
    raise KeyError(ch)


def glyph_img(ch):
    im = Image.new('RGBA', (CW, CH), (0, 0, 0, 0))
    base = ACC.get(ch, ch)
    rows = rows_of(base)
    w = max(len(r) for r in rows) if any(rows) else 1
    W = (255, 255, 255, 255)
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == '#': im.putpixel((x, y + TOP), W)
    if ch in ACC:
        lower = ch.islower()
        if lower and base == 'i':                      # í: accent replaces the dot
            im.putpixel((0, TOP), (0, 0, 0, 0)); im.putpixel((0, TOP + 1), (0, 0, 0, 0))
            w = 2
        ay = TOP + (0 if lower else -2)                # lower case: in the ascender space; caps: above
        if ch in 'Ññ':
            pts = [(0, ay + 1), (1, ay), (2, ay + 1), (3, ay)]
        elif ch in 'Üü':
            pts = [(0, ay + 1), (w - 1, ay + 1)]
        else:
            cx = min(w - 1, w // 2 + (0 if base != 'i' else 0))
            pts = [(cx, ay + 1), (min(w - 1, cx + 1), ay)] if base != 'i' else [(0, ay + 1), (1, ay)]
        for p in pts:
            if 0 <= p[0] < CW and 0 <= p[1] < CH: im.putpixel(p, W)
    return im, w


def build(out_png, out_json):
    chars = list(U) + list(L) + list(D) + list(ACC)
    cols = 16
    rows = (len(chars) + cols - 1) // cols
    atlas = Image.new('RGBA', (cols * CW, rows * CH), (0, 0, 0, 0))
    meta = []
    for i, ch in enumerate(chars):
        g, w = glyph_img(ch)
        x, y = (i % cols) * CW, (i // cols) * CH
        atlas.alpha_composite(g, (x, y))
        meta.append(dict(c=ord(ch), x=x, y=y, w=w, adv=w + 1))
    meta.append(dict(c=ord(' '), x=0, y=(rows - 1) * CH, w=0, adv=3))
    os.makedirs(os.path.dirname(out_png), exist_ok=True)
    atlas.save(out_png)
    json.dump(dict(cellW=CW, cellH=CH, ascent=TOP, size=CH, glyphs=meta), open(out_json, 'w'))
    return atlas.size, len(chars)


def preview(text_lines, out):
    """renders sample text with the atlas metrics (x4) for a visual check"""
    glyphs = {}
    for ch in list(U) + list(L) + list(D) + list(ACC): glyphs[ch] = glyph_img(ch)
    W = max(sum((glyphs[c][1] + 1) if c in glyphs else 3 for c in t) for t in text_lines) + 8
    im = Image.new('RGBA', (W, len(text_lines) * 12 + 6), (24, 20, 34, 255))
    for li, t in enumerate(text_lines):
        x = 4
        for c in t:
            if c in glyphs:
                im.alpha_composite(glyphs[c][0], (x, 3 + li * 12)); x += glyphs[c][1] + 1
            else: x += 3
    im.resize((im.width * 4, im.height * 4), Image.NEAREST).save(out)


